#!/usr/bin/env node
// Regenerates contract/omne-contract.json from a checkout of omne-harness-lite.
//
// The OMNE desktop client checks every skin member against the live interface: a token name it does not know, a
// part that does not open a layer, or an icon name it does not draw makes the whole skin fail to install. A client
// is not always connected while a skin is written, so this snapshot lets `npm run validate` apply the same rules
// offline. Run it again whenever the app moves on.
//
//   node scripts/sync-contract.mjs --source ../omne-harness-lite

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = fileURLToPath(new URL('.', import.meta.url))
const OUT = resolve(HERE, '..', 'contract', 'omne-contract.json')
const TOKEN_PREFIX = '--omne-'

function argument(name) {
  const at = process.argv.indexOf(name)
  return at === -1 ? undefined : process.argv[at + 1]
}

const source = resolve(argument('--source') ?? process.env.OMNE_SOURCE ?? '../omne-harness-lite')

const git = (...args) => execFileSync('git', ['-C', source, ...args], { encoding: 'utf8' }).trim()

/** Tracked files of the source that match one of the pathspecs. */
const tracked = (...specs) =>
  git('ls-files', '--', ...specs.map(spec => `:(glob)${spec}`))
    .split('\n')
    .filter(Boolean)

const read = path => readFileSync(join(source, path), 'utf8')

const withoutTests = path => !/(^|\/)(tests?|demo|e2e)\//u.test(path)

/**
 * The names under --omne- that a sheet sets in a rule whose selector holds :root, at any depth of @layer or @media,
 * and the names an @property registers: the same names the client knows (apps/desktop changes-sheet.ts tokenOf).
 */
function tokensIn(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//gu, '')
  const names = new Set()
  for (const match of text.matchAll(/@property\s+(--[A-Za-z0-9_-]+)/gu))
    if (match[1].startsWith(TOKEN_PREFIX)) names.add(match[1])
  const stack = []
  let start = 0
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index]
    if (char === '{') {
      stack.push(text.slice(start, index).trim())
      start = index + 1
    } else if (char === '}') {
      collect(text.slice(start, index))
      stack.pop()
      start = index + 1
    } else if (char === ';') {
      collect(text.slice(start, index + 1))
      start = index + 1
    }
  }
  function collect(declarations) {
    const selector = stack.at(-1) ?? ''
    if (!selector.includes(':root') || selector.startsWith('@')) return
    for (const match of declarations.matchAll(/(--[A-Za-z0-9_-]+)\s*:/gu))
      if (match[1].startsWith(TOKEN_PREFIX)) names.add(match[1])
  }
  return names
}

function tokens() {
  const names = new Set()
  for (const path of tracked('packages/**/*.css', 'apps/desktop/src/**/*.css').filter(withoutTests))
    for (const name of tokensIn(read(path))) names.add(name)
  return [...names].sort()
}

const quoted = /['"]([^'"]+)['"]/u

/** Every definePart({...}) in the sources: its name, the layers it opens and the part it is within. */
function parts() {
  const found = new Map()
  const files = tracked('packages/**/src/**/*.ts', 'packages/**/src/**/*.tsx', 'apps/**/src/**/*.ts', 'apps/**/src/**/*.tsx')
  for (const path of files.filter(withoutTests)) {
    const text = read(path)
    if (!text.includes('definePart')) continue
    for (const match of text.matchAll(/definePart(?:<[^>()]*>)?\(\{([\s\S]*?)\}\)/gu)) {
      const body = match[1]
      const name = body.match(/name:\s*['"]([^'"]+)['"]/u)?.[1]
      const depths = body.match(/depths:\s*\[([^\]]*)\]/u)?.[1]
      if (name === undefined || depths === undefined) continue
      const within = body.match(/within:\s*['"]([^'"]+)['"]/u)?.[1] ?? null
      const label = body.match(/label:\s*['"]([^'"]+)['"]/u)?.[1] ?? ''
      found.set(name, {
        name,
        label,
        within,
        depths: Array.from(depths.matchAll(new RegExp(quoted, 'gu')), each => each[1]),
        from: path,
      })
    }
  }
  return [...found.values()].sort((left, right) => (left.name < right.name ? -1 : 1))
}

function icons() {
  const names = new Set()
  for (const path of tracked('packages/frontend/ui-kit/src/**/*.ts', 'packages/frontend/ui-kit/src/**/*.tsx').filter(withoutTests))
    for (const match of read(path).matchAll(/defineIcon\(\s*['"]([^'"]+)['"]/gu)) names.add(match[1])
  return [...names].sort()
}

function pieces() {
  const text = read('packages/frontend/ui-kit/src/redraw/redraw.ts')
  const list = text.match(/PIECES\s*=\s*\[([^\]]*)\]/u)?.[1] ?? ''
  return Array.from(list.matchAll(new RegExp(quoted, 'gu')), each => each[1]).sort()
}

const contract = {
  $comment: 'Generated by scripts/sync-contract.mjs from omne-harness-lite. Do not edit by hand.',
  source: {
    repository: git('remote', 'get-url', 'origin'),
    commit: git('rev-parse', 'HEAD'),
    committed: git('log', '-1', '--format=%cs'),
  },
  tokens: tokens(),
  parts: parts(),
  icons: icons(),
  pieces: pieces(),
}

if (contract.tokens.length === 0 || contract.parts.length === 0)
  throw new Error(`found no tokens or no parts under ${source}: is it a checkout of omne-harness-lite?`)

writeFileSync(OUT, `${JSON.stringify(contract, null, 2)}\n`)
console.log(
  `wrote ${relative(process.cwd(), OUT)}: ${contract.tokens.length} tokens, ${contract.parts.length} parts, ` +
    `${contract.icons.length} icons, ${contract.pieces.length} pieces from ${contract.source.commit.slice(0, 12)}`,
)
